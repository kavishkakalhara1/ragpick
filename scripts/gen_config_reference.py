"""Generate docs/config-reference.md from the Pydantic config schema.

Usage:
    python scripts/gen_config_reference.py          # write the file
    python scripts/gen_config_reference.py --check  # exit 1 if it is out of date (CI)
"""

from __future__ import annotations

import sys
import types
import typing
from pathlib import Path

from pydantic import BaseModel
from pydantic.fields import FieldInfo
from pydantic_core import PydanticUndefined

from ragpick.config import (
    ApiKeySpec,
    CacheConfig,
    ComponentsConfig,
    ComponentSpec,
    EvalConfig,
    PriceSpec,
    QueryConfig,
    RagConfig,
    Requirements,
    RouterConfig,
    RouterSpec,
    RouteSpec,
    ServeConfig,
    TenancyConfig,
    TracingConfig,
)

OUT = Path(__file__).resolve().parent.parent / "docs" / "config-reference.md"
SECTIONS: list[tuple[str, type[BaseModel]]] = [
    ("Top level (`rag.yaml`)", RagConfig),
    ("`requirements`", Requirements),
    ("`components`", ComponentsConfig),
    ("Component spec (each entry of `components`, and `eval.judge`)", ComponentSpec),
    ("`query`", QueryConfig),
    ("`eval`", EvalConfig),
    ("Price spec (each entry of `eval.prices`)", PriceSpec),
    ("`tracing`", TracingConfig),
    ("`cache`", CacheConfig),
    ("`serve`", ServeConfig),
    ("`tenancy`", TenancyConfig),
    ("API key (each entry of `serve.api_keys`)", ApiKeySpec),
    ("Router config (top level of a router file)", RouterConfig),
    ("`router`", RouterSpec),
    ("Route (each entry of `router.routes`)", RouteSpec),
]


def type_name(annotation: object) -> str:
    """Readable name for a type annotation."""
    origin = typing.get_origin(annotation)
    args = typing.get_args(annotation)
    if origin is typing.Literal:
        return " \\| ".join(f"`{a}`" for a in args)
    if origin in (typing.Union, types.UnionType):
        return " \\| ".join(type_name(a) for a in args)
    if origin is not None:
        inner = ", ".join(type_name(a) for a in args)
        return f"{getattr(origin, '__name__', str(origin))}[{inner}]"
    if annotation is type(None):
        return "null"
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return annotation.__name__
    return getattr(annotation, "__name__", str(annotation))


def default_repr(field: FieldInfo) -> str:
    """Readable default value."""
    if field.is_required():
        return "**required**"
    if field.default_factory is not None:
        value = field.default_factory()  # type: ignore[call-arg]
    elif field.default is PydanticUndefined:
        return ""
    else:
        value = field.default
    if isinstance(value, BaseModel):
        return "see section"
    return f"`{value!r}`" if value not in (None, {}, []) else f"`{value}`"


def render() -> str:
    """Render the whole reference page."""
    lines = [
        "# Config reference",
        "",
        "<!-- Generated by scripts/gen_config_reference.py from ragpick.config. Do not edit. -->",
        "",
        "Layers merge in this order: **blueprint defaults → your `rag.yaml` → CLI `--set`**.",
        "Within `components`, changing a component's `type` replaces it entirely; keeping",
        "the type merges `params`. Strings may use `${ENV_VAR}` or `${ENV_VAR:-default}`.",
        "Relative paths (`data`, `index_dir`) resolve against the config file's directory.",
        "",
    ]
    for title, model in SECTIONS:
        lines += [f"## {title}", "", (model.__doc__ or "").strip(), ""]
        lines += ["| Key | Type | Default | Description |", "|---|---|---|---|"]
        for name, field in model.model_fields.items():
            description = (field.description or "").replace("|", "\\|")
            type_ = type_name(field.annotation)
            lines.append(f"| `{name}` | {type_} | {default_repr(field)} | {description} |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    """Write or check the reference."""
    content = render()
    if "--check" in sys.argv:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != content:
            print(f"{OUT} is out of date; run python scripts/gen_config_reference.py")
            return 1
        print(f"{OUT} is up to date")
        return 0
    OUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
